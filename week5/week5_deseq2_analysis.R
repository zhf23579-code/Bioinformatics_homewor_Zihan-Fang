suppressPackageStartupMessages({
  library(DESeq2)
  library(apeglm)
  library(tidyverse)
  library(ggrepel)
})

# ---- Import data ----
counts <- read.csv("homework/Week5_Homework_Count_Matrix.csv", row.names = 1, check.names = FALSE)
coldata <- read.csv("homework/Week5_Homework_Sample_Metadata.csv", row.names = 1, check.names = FALSE)

cat("Count matrix:", nrow(counts), "genes x", ncol(counts), "samples\n")

# ---- Mandatory validation ----
stopifnot(ncol(counts) == nrow(coldata))
stopifnot(identical(colnames(counts), rownames(coldata)))
stopifnot(all(counts >= 0))
stopifnot(all(as.matrix(counts) == round(as.matrix(counts))))

coldata$condition <- relevel(factor(coldata$condition), ref = "control")
coldata$batch <- factor(coldata$batch)

cat("\nExperimental design:\n")
print(table(coldata$batch, coldata$condition))
cat("\nLibrary size summary:\n")
print(summary(colSums(counts)))

# ---- Construct DESeq2 object with batch in design ----
dds <- DESeqDataSetFromMatrix(countData = counts, colData = coldata, design = ~ batch + condition)

# ---- Pre-filter ----
keep <- rowSums(counts(dds) >= 10) >= 3
cat("\nGenes before filtering:", nrow(dds), "\n")
dds <- dds[keep, ]
cat("Genes after filtering:", nrow(dds), "\n")

# ---- Fit model ----
dds <- DESeq(dds)

# ---- Inspect coefficient names ----
coef_names <- resultsNames(dds)
cat("\nCoefficients:\n")
print(coef_names)

target_coef <- "condition_treated_vs_control"
stopifnot(target_coef %in% coef_names)

# ---- Extract and shrink results ----
res <- results(dds, contrast = c("condition", "treated", "control"), alpha = 0.05)
res_shrunk <- lfcShrink(dds, coef = target_coef, type = "apeglm")

cat("\n=== Results summary ===\n")
print(summary(res_shrunk))

# ---- Build results dataframe ----
res_df <- as.data.frame(res_shrunk) |>
  rownames_to_column("gene_id") |>
  mutate(
    significant = !is.na(padj) & padj < 0.05 & abs(log2FoldChange) >= 1,
    direction = case_when(
      significant & log2FoldChange > 0 ~ "Up in treated",
      significant & log2FoldChange < 0 ~ "Down in treated",
      TRUE ~ "Not significant"
    )
  ) |>
  arrange(padj)

cat("\nSignificant genes (padj<0.05, |log2FC|>=1):", sum(res_df$significant), "\n")
print(table(res_df$direction))

# ---- Export results ----
write.csv(res_df, "week5_deseq2_results.csv", row.names = FALSE)

# ---- PCA plot ----
vsd <- varianceStabilizingTransformation(dds, blind = FALSE)
pca_df <- plotPCA(vsd, intgroup = c("condition", "batch"), returnData = TRUE)
percent_var <- round(100 * attr(pca_df, "percentVar"))

p_pca <- ggplot(pca_df, aes(x = PC1, y = PC2, color = condition, shape = batch, label = name)) +
  geom_point(size = 4) +
  geom_text_repel(size = 3, max.overlaps = Inf) +
  labs(title = "Week 5 RNA-seq PCA",
       x = paste0("PC1: ", percent_var[1], "% variance"),
       y = paste0("PC2: ", percent_var[2], "% variance"),
       color = "Condition", shape = "Batch") +
  theme_bw(base_size = 12)

ggsave("week5_pca.png", p_pca, width = 7, height = 5, dpi = 300)

# ---- Volcano plot ----
plot_df <- res_df |> mutate(neg_log10_padj = -log10(pmax(padj, 1e-300)))

p_volcano <- ggplot(plot_df, aes(x = log2FoldChange, y = neg_log10_padj, color = direction)) +
  geom_point(alpha = 0.7, size = 1.8) +
  geom_vline(xintercept = c(-1, 1), linetype = "dashed", color = "grey40") +
  geom_hline(yintercept = -log10(0.05), linetype = "dashed", color = "grey40") +
  scale_color_manual(values = c("Up in treated" = "#C0392B", "Down in treated" = "#2F6DB3",
                                 "Not significant" = "grey70")) +
  labs(title = "Differential Expression: Treated vs Control",
       subtitle = paste0("padj < 0.05, |log2FC| >= 1 | ", sum(res_df$significant), " significant genes"),
       x = "Shrunken log2 fold change (apeglm)", y = "-log10 adjusted p-value", color = NULL) +
  theme_bw(base_size = 12)

ggsave("week5_de_plot.png", p_volcano, width = 7, height = 5, dpi = 300)

